package seriesGenerator;

import java.util.Scanner;

public class square {
  
	public static void main (String[] args) throws java.lang.Exception
	{
      Scanner sc=new Scanner(System.in);
      
      int n=sc.nextInt();

      for(int i=1;i<=n;i++)
      {
        System.out.print(i*i+" ");
      }
      }
	}

